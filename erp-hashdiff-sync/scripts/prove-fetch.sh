#!/usr/bin/env bash
# Proof 06: a real fetch statement. Rebuild the ERP, run the first load of one
# table with the wrapper keeping statement text, and write each fetch batch's
# anatomy plus the first batch in full:
#   proofs/06-fetch-statement.md
#
#   scripts/prove-fetch.sh [table]    default ar_dunning, the table the essay shows
source "$(dirname "$0")/lib.sh"
table="${1:-ar_dunning}"
out=proofs/06-fetch-statement.md
wsql() { sql warehouse -d warehouse -h -1 -W "$@"; }

bash scripts/build-erp.sh 7 >/dev/null
wsql -Q "EXEC sync.usp_reset; EXEC sync.usp_probe_metadata;" >/dev/null
wsql -Q "UPDATE sync.config SET value = N'1' WHERE name = N'capture_sql';" >/dev/null
set +e
bash scripts/sync.sh "$table" >/dev/null
rc=$?
set -e
wsql -Q "UPDATE sync.config SET value = N'0' WHERE name = N'capture_sql';" >/dev/null
[[ $rc -eq 0 ]] || { echo "first load of $table failed"; exit 1; }

# One JSON document: the limit, the table, and every fetch statement in call order.
json=$(mktemp)
trap 'rm -f "$json"' EXIT
sql warehouse -d warehouse -y 0 -Q "SET NOCOUNT ON;
SELECT (SELECT
    (SELECT CAST(value AS int) FROM sync.config WHERE name = N'text_limit') AS text_limit,
    m.table_name, m.key_columns,
    (SELECT COUNT(*) FROM sync.source_columns s WHERE s.table_name = m.table_name) AS columns,
    (SELECT d.sql_chars, d.rows_back, d.sql_text FROM sync.driver_log d
     WHERE d.caller LIKE N'%:' + m.table_name AND d.sql_text LIKE N'% JOIN (VALUES %'
     ORDER BY d.call_id FOR JSON PATH) AS batches
  FROM sync.manifest m WHERE m.table_name = N'$table'
  FOR JSON PATH, WITHOUT_ARRAY_WRAPPER)" > "$json"

python3 - "$json" "$(date -u +%Y-%m-%d)" > "$out" <<'EOF'
import json, re, sys
raw = open(sys.argv[1], encoding='utf-8').read()
d = json.loads(raw[raw.index('{'):raw.rindex('}') + 1])
limit, t, batches = d['text_limit'], d['table_name'], d['batches']
pat = re.compile(r"SELECT (.*) FROM (\S+ s) JOIN \(VALUES (.*)\) (v\(.*?\)) ON (.*)$", re.S)
tup = re.compile(r"\((?:[^()']|'(?:[^']|'')*')*\)")
rows = []
for b in batches:
    sql = b['sql_text']
    assert len(sql) == b['sql_chars']
    cols, frm, vals, alias, on = pat.match(sql).groups()
    keys = tup.findall(vals)
    assert ','.join(keys) == vals, 'tuples do not rebuild the VALUES list'
    rows.append(dict(sql=sql, cols=cols, frm=frm, vals=vals, alias=alias, on=on, keys=keys,
                     fixed=len(sql) - len(vals), rows_back=b['rows_back']))
assert all(r['rows_back'] == len(r['keys']) for r in rows), 'a batch returned other than one row per key'
first = rows[0]
lens = [len(k) for k in first['keys']]
per_key = (len(first['vals']) + 1) / len(first['keys'])
room = limit - first['fixed']
n = lambda x: f"{x:,}"

print("# Fetch statement proof\n")
print(f"Generated by `scripts/prove-fetch.sh`. Do not edit by hand. Run on {sys.argv[2]}.\n")
print("The ERP is read-only, so the sync cannot hand it a table of keys to join to. Step 5 puts the keys in the "
      "statement itself, as literal tuples in a `VALUES` list, and runs it on the ERP through `EXEC (...) AT ERP`. "
      "The text limit then decides how many keys one statement can carry.\n")
print(f"This is the first load of `{t}` ({d['columns']} columns, key {', '.join(k.strip() for k in d['key_columns'].split(','))}) on the stand-in ERP, "
      "with the wrapper set to keep each statement's text. That setting is test scaffolding for this proof; normal runs log "
      "only each statement's length.\n")
print("## How the batches fill the text limit\n")
print("Every batch of a table shares the same fixed text: the select list, the `FROM`, and the join. The rest of the limit "
      "is room for key literals, each followed by a comma. A batch closes before the next literal could overflow, keeping "
      "one longest literal's worth of space spare.\n")
print("| Batch | Keys | Fixed text | Key literals | Statement | Under the limit | Rows returned |")
print("|---|---|---|---|---|---|---|")
for i, r in enumerate(rows, 1):
    print(f"| {i} | {n(len(r['keys']))} | {n(r['fixed'])} | {n(len(r['vals']))} | {n(len(r['sql']))} | "
          f"{n(limit - len(r['sql']))} | {n(r['rows_back'])} |")
print()
print(f"The arithmetic: the limit, {n(limit)} characters, minus {n(first['fixed'])} of fixed text leaves {n(room)} for keys. "
      f"Batch 1's {n(len(first['keys']))} literals run {min(lens)} to {max(lens)} characters, {per_key:.1f} on average with the comma, "
      f"and fill {n(len(first['vals']))} of the {n(room)}: one more would not fit with a longest literal's worth to spare. "
      "Each batch returned exactly one row per key it sent.\n")
print("## Batch 1, in full\n")
print(f"Sent as one line of {n(len(first['sql']))} characters; shown here with one column and one key per line, "
      "and otherwise unchanged. A quoted code is escaped by doubling the quote: the code `L'3` goes in as `'L''3'`.\n")
print("```sql")
c = first['cols'].split(',')
print("SELECT " + c[0])
for x in c[1:]:
    print("     , " + x)
print(f"FROM {first['frm']}")
print("JOIN (VALUES")
for i, k in enumerate(first['keys']):
    print("      " + k + ("," if i < len(first['keys']) - 1 else ""))
print(f"     ) {first['alias']}")
conds = first['on'].split(' AND ')
print("  ON " + conds[0])
for x in conds[1:]:
    print(" AND " + x)
print("```\n")
print(f"The procedure runs each batch as `INSERT INTO stage.[{t}__rows] (...) EXEC sync.erp_exec_at @remote, @caller`, "
      "and the wrapper sends it with `EXEC (@sql) AT ERP`.")
EOF
echo "wrote $out"
