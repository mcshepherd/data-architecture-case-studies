#!/usr/bin/env bash
# Milestone 0 proof: the warehouse reaches the ERP only through a linked server
# that is read-only and enforces a hard query timeout.
source "$(dirname "$0")/lib.sh"
out=proofs/00-infrastructure.md

# run <title> <expectation> <T-SQL sent to the ERP via EXEC AT>
q="'"
run() {
    local escaped="${3//$q/$q$q}" started ended rc output
    started=$(date +%s)
    set +e
    output=$(sql warehouse -W -Q "EXEC ('$escaped') AT ERP" 2>&1)
    rc=$?
    set -e
    ended=$(date +%s)
    {
        echo "## $1"
        echo
        echo "$2"
        echo
        echo '```sql'
        echo "EXEC ('$escaped') AT ERP"
        echo '```'
        echo
        echo "Exit code $rc after $((ended - started))s:"
        echo
        echo '```'
        echo "$output"
        echo '```'
        echo
    } >> "$out"
}

{
    echo "# Infrastructure proof"
    echo
    echo "Generated by \`scripts/prove-infra.sh\`. Do not edit by hand."
    echo
    echo "Two SQL Server 2022 instances: \`erp\` (the stand-in vendor ERP) and \`warehouse\`. The warehouse reaches the ERP only through the linked server \`ERP\`, as \`erp_reader\`, a login with read-only access. The linked server's query timeout is ${QUERY_TIMEOUT_S}s, standing in for the vendor driver's 15-minute hard timeout at reduced scale."
    echo
    echo "Run on $(date -u +%Y-%m-%d)."
    echo
} > "$out"

run "Reads work" "Expected: succeeds, connected as erp_reader." \
    "SELECT SUSER_NAME() AS login_name, DB_NAME() AS database_name"
run "Nothing can be created on the source" "Expected: permission denied. The process has to do all staging on the warehouse side." \
    "CREATE TABLE dbo.staging_probe (id int)"
# A table that exists on the ERP, so the write test is a write, not DDL.
sql erp -Q "USE erp; IF OBJECT_ID('dbo.write_probe') IS NULL CREATE TABLE dbo.write_probe (id int);" >/dev/null
run "Nothing can be written on the source" "Expected: permission denied, on a table that exists." \
    "INSERT INTO dbo.write_probe (id) VALUES (1)"
sql erp -Q "USE erp; DROP TABLE dbo.write_probe;" >/dev/null
run "Queries are killed at the timeout" "Expected: cancelled at ${QUERY_TIMEOUT_S}s, although the query would finish at $((QUERY_TIMEOUT_S + 10))s. Note the exit code: the provider reports the timeout as an informational message, not an error." \
    "WAITFOR DELAY '00:00:$((QUERY_TIMEOUT_S + 10))'; SELECT 1 AS finished"

# Rows that keep arriving are not cut off. Three chunks of rows with pauses
# shorter than the timeout, so the query runs past the timeout in total.
pause=$((QUERY_TIMEOUT_S * 2 / 3))
chunk="SELECT TOP (50000) REPLICATE('x', 200) AS r FROM sys.all_objects a CROSS JOIN sys.all_objects b"
stream="$chunk; WAITFOR DELAY '00:00:$pause'; $chunk; WAITFOR DELAY '00:00:$pause'; $chunk"
started=$(date +%s)
set +e
output=$(sql warehouse -h -1 -W -Q "SET NOCOUNT ON; EXEC ('${stream//$q/$q$q}') AT ERP" 2>&1)
rc=$?
set -e
ended=$(date +%s)
{
    echo "## Queries that keep returning rows run past the timeout"
    echo
    echo "Expected: all 150,000 rows arrive, although the query runs past the ${QUERY_TIMEOUT_S}s timeout, because no pause between rows is as long as the timeout. The timeout limits how long the provider waits for rows, not how long a query runs. A query that computes before its first row, such as the one above, must finish inside the timeout; one that streams rows need not. The vendor driver behaved the same way."
    echo
    echo '```sql'
    echo "EXEC ('${stream//$q/$q$q}') AT ERP"
    echo '```'
    echo
    echo "Exit code $rc after $((ended - started))s: $(grep -c '^x' <<<"$output") rows returned."
    grep -v '^x' <<<"$output" | sed '/^$/d' | sed 's/^/    /' || true
    echo
} >> "$out"

{
    echo "## Timeouts are silent inside a procedure"
    echo
    echo "Expected: the same timeout inside TRY/CATCH raises no error and pulls zero rows. A pull that times out looks exactly like a table with no rows. Any step that trusts an empty result would treat every local row as deleted, so the process must check row counts rather than rely on errors."
    echo
    echo '```sql'
    sed "s/\$(WAIT_S)/$((QUERY_TIMEOUT_S + 10))/" sql/proofs/00_silent_timeout.sql
    echo '```'
    echo
    echo '```'
    sql warehouse -W -d warehouse -v WAIT_S=$((QUERY_TIMEOUT_S + 10)) -i /sql/proofs/00_silent_timeout.sql 2>&1
    echo '```'
    echo
} >> "$out"

echo "wrote $out"
