#!/usr/bin/env bash
# Milestones 2 and 3: rebuild the ERP, then run the first load and N nights.
# Each night: the ERP's business activity, the new sync, the old SSIS-style
# package, and an independent audit of both copies. Writes two proofs:
#   proofs/02-nightly-correctness.md   the new process
#   proofs/03-old-versus-new.md        the old process against the new
#
#   scripts/prove-nightly.sh [nights]    default 7; about an hour
source "$(dirname "$0")/lib.sh"
nights="${1:-7}"
wsql() { sql warehouse -d warehouse -h -1 -W "$@"; }
run_at() { python3 -c "import datetime,sys; print((datetime.datetime(2026,1,1,2,0)+datetime.timedelta(days=int(sys.argv[1]))).strftime('%Y-%m-%d %H:%M'))" "$1"; }
one_night() {
    local n="$1" at; at="$(run_at "$n")"
    bash scripts/sync.sh --run-at "$at" || true
    wsql -Q "SET NOCOUNT ON; DECLARE @r int; EXEC legacy.usp_run @run_at = '$at', @run_id = @r OUTPUT;"
    wsql -Q "SET NOCOUNT ON; DECLARE @r int = (SELECT MAX(run_id) FROM sync.run); EXEC audit.usp_audit_run @r, 'replica';
             SET @r = (SELECT MAX(run_id) FROM legacy.run); EXEC audit.usp_audit_run @r, 'legacy';"
}

bash scripts/build-erp.sh 7 >/dev/null
wsql -Q "EXEC sync.usp_reset; EXEC legacy.usp_reset; DELETE FROM audit.result; EXEC sync.usp_probe_metadata;" >/dev/null

echo "first load"
one_night 0
for n in $(seq 1 "$nights"); do
    echo "night $n"
    sql erp -d erp_sim -Q "EXEC dbo.usp_run_night $n" >/dev/null
    one_night "$n"
done

stamp="Do not edit by hand. Run on $(date -u +%Y-%m-%d)."
{
    echo "# Nightly correctness proof"
    echo
    echo "Generated by \`scripts/prove-nightly.sh $nights\`. $stamp"
    echo
    sql warehouse -h -1 -i /sql/proofs/02_report.sql
    sql erp -h -1 -i /sql/proofs/02_erp_activity.sql
} | grep -v '^Changed database context' > proofs/02-nightly-correctness.md
{
    echo "# Old process against new"
    echo
    echo "Generated by \`scripts/prove-nightly.sh $nights\`. $stamp"
    echo
    sql warehouse -h -1 -i /sql/proofs/03_report.sql
} | grep -v '^Changed database context' > proofs/03-old-versus-new.md
echo "wrote proofs/02-nightly-correctness.md and proofs/03-old-versus-new.md"
