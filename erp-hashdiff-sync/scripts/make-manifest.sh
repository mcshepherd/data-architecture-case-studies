#!/usr/bin/env bash
# Write sql/warehouse/20_manifest.sql from the stand-in ERP's design.
#
# At the original site the manifest was maintained by hand from the vendor's data
# dictionary, because the ERP's catalog declares no keys. Here the stand-in's
# designer knows the keys, so the manifest is generated once and committed. The
# sync never reads the design; it reads only this manifest.
source "$(dirname "$0")/lib.sh"
out=sql/warehouse/20_manifest.sql
{
    echo "-- Table manifest: the tables to replicate and their key columns."
    echo "-- Generated by scripts/make-manifest.sh from the stand-in ERP's design; see that script."
    echo "-- Runs on the warehouse instance."
    echo
    echo "USE warehouse;"
    echo "GO"
    echo
    echo "DELETE FROM sync.manifest;"
    echo "INSERT INTO sync.manifest (table_name, key_columns) VALUES"
    sql erp -d erp_sim -h -1 -W -Q "SET NOCOUNT ON;
        SELECT CONCAT('    (''', d.table_name, ''', ''', k.keys, ''')',
                      IIF(ROW_NUMBER() OVER (ORDER BY d.table_name DESC) = 1, ';', ','))
        FROM dbo.design_table d
        CROSS APPLY (SELECT STRING_AGG(column_name, ', ') WITHIN GROUP (ORDER BY key_ordinal) AS keys
                     FROM dbo.design_column c WHERE c.table_name = d.table_name AND c.role = 'key') k
        ORDER BY d.table_name;"
    echo "GO"
} > "$out"
echo "wrote $out ($(grep -c "^    (" "$out") tables)"
