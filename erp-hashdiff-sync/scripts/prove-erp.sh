#!/usr/bin/env bash
# Milestone 1 proof: the stand-in ERP, what the warehouse can see of it, and the
# wrapper that enforces the driver's text limit and hard timeout.
source "$(dirname "$0")/lib.sh"
out=proofs/01-stand-in-erp.md
{
    echo "# Stand-in ERP proof"
    echo
    echo "Generated by \`scripts/prove-erp.sh\`. Do not edit by hand. Run on $(date -u +%Y-%m-%d)."
    echo
    sql erp -h -1 -i /sql/proofs/01_erp_summary.sql
    echo
    echo "## What the warehouse sees"
    echo
    echo "Everything below goes through \`sync.erp_exec_at\`, as the read-only \`erp_reader\`."
    echo
    sql warehouse -h -1 -i /sql/proofs/01_warehouse_view.sql
    echo
    echo "## The driver's limits"
    echo
    echo "\`sync.erp_exec_at\` is the only way to run a statement on the ERP. It rejects statements over the text limit before sending them, and raises a hard error when a statement runs to the linked server's ${QUERY_TIMEOUT_S}s timeout, as the vendor driver did. Without the wrapper, the timeout is only an informational message from the provider and no error is raised (see [00-infrastructure](00-infrastructure.md)). From [\`sql/proofs/01_wrapper.sql\`](../sql/proofs/01_wrapper.sql):"
    echo
    sql warehouse -h -1 -v WAIT_S=$((QUERY_TIMEOUT_S + 10)) -i /sql/proofs/01_wrapper.sql 2>&1 | grep -v 'returned message "Query timeout expired"'
} | grep -v '^Changed database context' > "$out"
echo "wrote $out"
