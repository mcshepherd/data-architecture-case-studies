#!/usr/bin/env bash
# Milestone 4: failure, recovery, and hashing edge cases. Rebuilds the ERP, runs
# the first load, then works through each scenario, auditing after each.
# Writes proofs/04-failure-and-recovery.md and proofs/05-hashing-edge-cases.md.
# About 20 minutes.
source "$(dirname "$0")/lib.sh"
wq() { sql warehouse -d warehouse -h -1 -W -Q "SET NOCOUNT ON; $1"; }
eq() { sql erp -d erp_sim -h -1 -W -Q "SET NOCOUNT ON; $1"; }
night=0
at() { python3 -c "import datetime,sys; print((datetime.datetime(2026,1,1,2,0)+datetime.timedelta(days=int(sys.argv[1]))).strftime('%Y-%m-%d %H:%M'))" "$1"; }
next_night() { night=$((night + 1)); eq "EXEC dbo.usp_run_night $night" >/dev/null; }
sync_night() { bash scripts/sync.sh --run-at "$(at "$night")" "$@" >/dev/null || true; }
run() { wq "SELECT MAX(run_id) FROM sync.run"; }
attempts() {  # every attempt at a table in the last run
    wq "SELECT STRING_AGG(CONCAT(status, IIF(status = 'succeeded' AND batch_retries > 0, CONCAT(' after ', batch_retries, ' batch retries'), ''),
                                 IIF(message IS NULL, '', CONCAT(' (', message, ')'))), '; then ') WITHIN GROUP (ORDER BY log_id)
        FROM sync.run_table_log WHERE run_id = (SELECT MAX(run_id) FROM sync.run) AND table_name = N'$1'"
}
fingerprint() {
    wq "SELECT CONCAT(FORMAT(COUNT(*), 'N0'), ' rows, ', FORMAT(SUM(CAST(_is_deleted AS int)), 'N0'), ' flagged deleted, checksum ',
                      CHECKSUM_AGG(CHECKSUM(_row_hash, _loaded_at, _is_deleted))) FROM replica.[$1]"
}
audit_one() {
    wq "DECLARE @r int = (SELECT MAX(run_id) FROM sync.run); EXEC audit.usp_audit_table N'$1', @r, 'replica';
        SELECT IIF(problems = 0, 'clean',
                   CONCAT(missing, ' missing, ', extra, ' extra, ', mismatched, ' stale')) FROM audit.result
        WHERE copy_name = 'replica' AND run_id = @r AND table_name = N'$1'"
}
logged() { wq "SELECT CONCAT(ISNULL($2, 0), '') FROM sync.run_table_log WHERE log_id = (SELECT MAX(log_id) FROM sync.run_table_log WHERE table_name = N'$1')"; }

# Mailpit must be up before anything is reset: the proof reads alert emails from it.
mailpit=http://127.0.0.1:18025/api/v1
curl -sf "$mailpit/info" >/dev/null || { echo "Mailpit is not reachable at $mailpit; run scripts/up.sh" >&2; exit 1; }

echo "rebuild and first load"
bash scripts/build-erp.sh 7 >/dev/null
sql erp -i /sql/erp/30_sim_scenarios.sql >/dev/null
wq "EXEC sync.usp_reset; DELETE FROM audit.result; EXEC sync.usp_probe_metadata;" >/dev/null
curl -sf -X DELETE "$mailpit/messages" >/dev/null  # empty the inbox
sync_night
f04=proofs/04-failure-and-recovery.md
{
    echo "# Failure and recovery proof"
    echo
    echo "Generated by \`scripts/prove-resilience.sh\`. Do not edit by hand. Run on $(date -u +%Y-%m-%d)."
    echo
    echo "Each scenario runs on a real night of ERP activity, with a fault injected where noted. Faults are injected in \`sync.erp_exec_at\` and fail exactly as the driver's timeout does (error 50002). The runner gives each table up to three attempts; inside each attempt, each fetch batch gets up to three."
    echo
} > "$f04"

echo "A: batch failures, recovered by batch retries"
next_night
wq "EXEC sync.usp_arm_fault N'%:tm_timesheet_3', N'%JOIN (VALUES%', 2" >/dev/null
sync_night
A_run=$(run); A_att=$(attempts tm_timesheet_3); A_aud=$(audit_one tm_timesheet_3)

echo "B: a table attempt fails, the runner's retry succeeds"
next_night
wq "EXEC sync.usp_arm_fault N'%:pj_project', N'%JOIN (VALUES%', 3" >/dev/null
sync_night
B_run=$(run); B_att=$(attempts pj_project); B_aud=$(audit_one pj_project)

echo "C: a table fails for the night, then heals"
next_night
C_before=$(fingerprint bl_fee)
wq "EXEC sync.usp_arm_fault N'%:bl_fee', N'%JOIN (VALUES%', 9" >/dev/null
sync_night
C_run=$(run); C_att=$(attempts bl_fee); C_after=$(fingerprint bl_fee); C_aud=$(audit_one bl_fee)
next_night
sync_night
C_heal=$(attempts bl_fee); C_heal_aud=$(audit_one bl_fee)

echo "D: the key-and-hash pull times out"
next_night
wq "EXEC sync.usp_arm_fault N'%:gl_period_5', N'%DECLARE @d%', 1" >/dev/null
sync_night
D_run=$(run); D_att=$(attempts gl_period_5); D_aud=$(audit_one gl_period_5)

echo "E: variance guard"
next_night
E_before=$(fingerprint pj_project)
eq "EXEC dbo.usp_hold_rows N'pj_project', 5" >/dev/null
E_held=$(eq "SELECT FORMAT(COUNT(*), 'N0') FROM dbo.hold__pj_project")
sync_night
E_run=$(run); E_att=$(attempts pj_project); E_after=$(fingerprint pj_project)
eq "EXEC dbo.usp_restore_rows N'pj_project'" >/dev/null
next_night
sync_night
E_heal=$(attempts pj_project); E_heal_aud=$(audit_one pj_project)

echo "F: wipe and reload, then a full audit"
wq "DELETE FROM sync.fault" >/dev/null
F_start=$(date +%s)
bash scripts/sync.sh --run-at "$(at "$night")" --wipe >/dev/null || true
F_secs=$(( $(date +%s) - F_start ))
F_ok=$(wq "SELECT COUNT(*) FROM sync.run_table_log WHERE run_id = (SELECT MAX(run_id) FROM sync.run) AND status = 'succeeded'")
F_rows=$(wq "SELECT FORMAT(SUM(inserted), 'N0') FROM sync.run_table_log WHERE run_id = (SELECT MAX(run_id) FROM sync.run) AND status = 'succeeded'")
wq "DECLARE @r int = (SELECT MAX(run_id) FROM sync.run); EXEC audit.usp_audit_run @r, 'replica';" >/dev/null
F_aud=$(wq "SELECT CONCAT(SUM(IIF(problems = 0, 1, 0)), ' of ', COUNT(*), ' tables clean')
            FROM audit.result WHERE copy_name = 'replica' AND run_id = (SELECT MAX(run_id) FROM sync.run)")

{
    echo "| Scenario | Injected | What the process did | Replica | Audit |"
    echo "|---|---|---|---|---|"
    echo "| **A. Batch failures** on \`tm_timesheet_3\`, night 1 | 2 fetch batches time out | $A_att | Updated | $A_aud |"
    echo "| **B. A table attempt fails** on \`pj_project\`, night 2 | 3 fetch calls time out: one batch fails all three of its tries | $B_att | Updated on the second attempt | $B_aud |"
    echo "| **C. A table fails for the night** on \`bl_fee\`, night 3 | 9 fetch calls time out: every attempt fails | $C_att | Untouched. Before: $C_before. After: $C_after. | $C_aud: that night's changes not yet applied, nothing half-applied |"
    echo "| **C, next night** | nothing | $C_heal | Caught up: two nights of changes applied | $C_heal_aud |"
    echo "| **D. The key-and-hash pull times out** on \`gl_period_5\`, night 5 | 1 pull times out | $D_att | Updated on the second attempt | $D_aud |"
    echo "| **E. A short pull** on \`pj_project\`, night 6 | $E_held rows (5%) vanish from the ERP, as in a partial restore | $E_att | Untouched: no mass soft-delete. Before: $E_before. After: $E_after. | not audited: the ERP was short that night |"
    echo "| **E, next night** | rows restored | $E_heal | Caught up | $E_heal_aud |"
    echo "| **F. Wipe and reload** of every table | \`--wipe\` | $F_ok of 120 tables reloaded through the normal path, $F_rows rows, in $((F_secs / 60)) min $((F_secs % 60)) s | Rebuilt from scratch | $F_aud |"
    echo
    echo "- **A and B:** retries are nested. A failed batch is retried inside the procedure; a table whose batch fails three times is retried by the runner. A failed \`INSERT ... EXEC\` inserts nothing, so a retry never duplicates rows."
    echo "- **C:** nothing is applied until every batch has been fetched and staged, and then everything is applied in one transaction. A table that fails is left exactly as it was the night before, and the next run picks up everything it missed."
    echo "- **E:** the guard compares the pulled key count with the replica's active rows. Without it, the vanished rows would have been flagged deleted, and restored the next night. The breach is logged and not retried."
} >> "$f04"

echo "alerts"
# Wait for Database Mail to finish, then check every alert reached the inbox.
for _ in $(seq 1 30); do
    [[ $(wq "SELECT COUNT(*) FROM msdb.dbo.sysmail_unsentitems") == 0 ]] && break
    sleep 2
done
sleep 3
failed_mail=$(wq "SELECT COUNT(*) FROM msdb.dbo.sysmail_faileditems f JOIN sync.alert a ON a.mailitem_id = f.mailitem_id")
alerts_logged=$(wq "SELECT COUNT(*) FROM sync.alert")
inbox=$(curl -sf "$mailpit/messages" | python3 -c "import json,sys; print(json.load(sys.stdin)['messages_count'])")
if [[ "$failed_mail" != 0 || "$inbox" != "$alerts_logged" ]]; then
    echo "alert delivery check failed: $alerts_logged alerts logged, $inbox in the inbox, $failed_mail failed in Database Mail" >&2
    exit 1
fi
runs=$(wq "SELECT COUNT(*) FROM sync.run")
python3 - "$runs" "A=$A_run" "B=$B_run" "C=$C_run" "D=$D_run" "E=$E_run" >> "$f04" <<'PY'
import json, re, sys, urllib.request
api = "http://127.0.0.1:18025/api/v1"
runs = int(sys.argv[1])
scenario = dict(a.split("=") for a in sys.argv[2:])
msgs = json.load(urllib.request.urlopen(f"{api}/messages"))["messages"]
msgs.sort(key=lambda m: m["Created"])
emailed = {re.match(r"\[sync\] Run (\d+):", m["Subject"]).group(1) for m in msgs}
quiet = [name for name, run in sorted(scenario.items()) if run not in emailed]
alerted = [name for name, run in sorted(scenario.items()) if run in emailed]
def names(xs):
    return xs[0] if len(xs) == 1 else ", ".join(xs[:-1]) + " and " + xs[-1]
print()
print("## Alerts")
print()
print(f"The runner calls `sync.usp_alert_run` at the end of every run, as the original SSIS package ran a Send Mail task on failure: "
      f"one email per run, and only if a table ended the run anything but succeeded. It goes out through Database Mail to Mailpit, which catches it. "
      f"Over the {runs} runs above, {len(msgs)} email{'s' if len(msgs) != 1 else ''} went out, "
      f"for scenario{'s' if len(alerted) != 1 else ''} {names(alerted) if alerted else 'none'}. "
      + (f"Scenario{'s' if len(quiet) != 1 else ''} {names(quiet)} sent none: every table there ended its run succeeded, even where an attempt failed along the way. " if quiet else "")
      + "Every alert logged in `sync.alert` reached the inbox, and none failed in Database Mail.")
for m in msgs:
    full = json.load(urllib.request.urlopen(f"{api}/message/{m['ID']}"))
    to = ", ".join(a["Address"] for a in full["To"])
    print()
    print(f"**{full['Subject']}** (to {to}, via Database Mail)")
    print()
    print("```")
    print(full["Text"].strip())
    print("```")
PY

echo "edge cases"
key_table=$(eq "SELECT dbo.key_case_table()")
case5_table=$(eq "SELECT table_name FROM dbo.case5_pair()")
eq "DELETE FROM dbo.edge_log; EXEC dbo.usp_edge_case 5, 1; EXEC dbo.usp_edge_case 6, 1;" >/dev/null
bash scripts/sync.sh --run-at "$(at "$night")" tm_expense_3 pj_milestone "$case5_table" >/dev/null
rows=()
for n in 1 2 3 4 5 6; do
    eq "EXEC dbo.usp_edge_case $n" >/dev/null
    t=$(eq "SELECT table_name FROM dbo.edge_log WHERE case_no = $n")
    bash scripts/sync.sh --run-at "$(at "$night")" "$t" >/dev/null
    line=$(eq "SELECT CONCAT('| ', title, ' | \`', table_name, '.', REPLACE(column_name, ', ', '\`, \`'), '\` | ', REPLACE(before_value, '|', '\|'), ' | ', REPLACE(after_value, '|', '\|'),
                             ' | ', IIF(naive_same = 1, '**No**', 'Yes')) FROM dbo.edge_log WHERE case_no = $n")
    rows+=("$line | $(logged "$t" changed_keys) changed | $(audit_one "$t") |")
done
eq "EXEC dbo.usp_key_case 7" >/dev/null
bash scripts/sync.sh --run-at "$(at "$night")" "$key_table" >/dev/null
rows+=("| a new key whose code contains quotes | \`$key_table\` | — | code \`O'Brien's\` | — | $(logged "$key_table" new_keys) new | $(audit_one "$key_table") |")
eq "EXEC dbo.usp_key_case 8, 1" >/dev/null
bash scripts/sync.sh --run-at "$(at "$night")" "$key_table" >/dev/null
k8a="$(logged "$key_table" deleted_keys) deleted"
eq "EXEC dbo.usp_key_case 8, 2" >/dev/null
bash scripts/sync.sh --run-at "$(at "$night")" "$key_table" >/dev/null
rows+=("| a deleted key is re-created with new values | \`$key_table\` | row present | deleted, then re-created | — | $k8a, then $(logged "$key_table" changed_keys) changed | $(audit_one "$key_table") |")

{
    echo "# Hashing edge cases"
    echo
    echo "Generated by \`scripts/prove-resilience.sh\`. Do not edit by hand. Run on $(date -u +%Y-%m-%d)."
    echo
    echo "Each case makes one targeted change to one row in the ERP, then runs the sync on that table and audits it. The \"naive hash\" column shows whether an obvious first-draft row hash would even notice: text as-is, everything else by default conversion, NULL as an empty string, a single-pipe delimiter, and no \`varchar(max)\`. Where it says **No**, a sync built on it would silently keep the old row."
    echo
    echo "| Change | Column | Before | After | Naive hash sees it? | Sync | Audit |"
    echo "|---|---|---|---|---|---|---|"
    printf '%s\n' "${rows[@]}"
    echo
    echo "Why the sync's hash sees every one:"
    echo
    echo "- **NULL versus empty string:** NULL is replaced by \`CHAR(0)\`, which no text value contains, so NULL and \`''\` hash differently."
    echo "- **money, float, datetime:** each type is cast with an explicit style that keeps full precision: money style 2 (four decimals), float style 3 (17 significant digits), datetime style 121 (milliseconds). The default conversions round money to two decimals, float to six significant digits, and datetime to the minute."
    echo "- **A pipe moving between columns:** the delimiter is \`\$|\$\`. With a single pipe, \`'ab|' + '|' + 'cd'\` and \`'ab' + '|' + '|cd'\` are the same string."
    echo "- **Past 4,000 characters:** the concatenation starts from a \`varchar(max)\`. Without one, SQL Server silently truncates it: at 8,000 characters, or at 4,000 as soon as an \`nvarchar\` column joins in. The row here is about 7,650 characters, and the change is near its end."
    echo "- **Quotes in keys:** keys go back to the ERP as literals in a \`VALUES\` list, with every quote doubled. One unescaped quote would break the whole batch."
    echo "- **A re-created key:** a key that disappears is flagged deleted; when it comes back, it is treated as changed, so the old row is replaced rather than left flagged."
} > proofs/05-hashing-edge-cases.md
echo "wrote $f04 and proofs/05-hashing-edge-cases.md"
