#!/usr/bin/env bash
# Milestone 2 proof: rebuild the ERP, run the first load and N nights of ERP
# activity, sync after each, audit after each, and write the report.
#
#   scripts/prove-sync.sh [nights]    default 7
source "$(dirname "$0")/lib.sh"
nights="${1:-7}"
out=proofs/02-nightly-correctness.md
wsql() { sql warehouse -d warehouse -h -1 -W "$@"; }
audit_last() { wsql -Q "SET NOCOUNT ON; DECLARE @r int = (SELECT MAX(run_id) FROM sync.run); EXEC audit.usp_audit_run @r;"; }

bash scripts/build-erp.sh 7 >/dev/null
wsql -Q "EXEC sync.usp_reset; DELETE FROM audit.result; EXEC sync.usp_probe_metadata;" >/dev/null

echo "first load"
bash scripts/sync.sh --run-at "2026-01-01 02:00" || true
audit_last
for n in $(seq 1 "$nights"); do
    echo "night $n"
    sql erp -d erp_sim -Q "EXEC dbo.usp_run_night $n" >/dev/null
    bash scripts/sync.sh --run-at "$(date -j -v+"${n}"d -f '%Y-%m-%d %H:%M' '2026-01-01 02:00' '+%Y-%m-%d %H:%M')" || true
    audit_last
done

{
    echo "# Nightly correctness proof"
    echo
    echo "Generated by \`scripts/prove-sync.sh $nights\`. Do not edit by hand. Run on $(date -u +%Y-%m-%d)."
    echo
    sql warehouse -h -1 -i /sql/proofs/02_report.sql
    sql erp -h -1 -i /sql/proofs/02_erp_activity.sql
} | grep -v '^Changed database context' > "$out"
echo "wrote $out"
