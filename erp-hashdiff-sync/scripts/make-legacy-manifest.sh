#!/usr/bin/env bash
# Write sql/warehouse/50_legacy_manifest.sql: how the old SSIS package loaded each table.
#
# Tables of 20,000 rows or more that carry create and modify dates were loaded
# incrementally: rows dated within the last 7 or 30 days, upserted on a key
# that omits the last column of the real composite key. Everything else was
# fully reloaded. At the original site the split was "full reload takes longer
# than the timeout"; at this scale no full reload does, so size stands in.
source "$(dirname "$0")/lib.sh"
out=sql/warehouse/50_legacy_manifest.sql
{
    echo "-- How the old SSIS package loaded each table."
    echo "-- Generated by scripts/make-legacy-manifest.sh from the stand-in ERP's design; see that script."
    echo "-- Runs on the warehouse instance."
    echo
    echo "USE warehouse;"
    echo "GO"
    echo
    echo "IF SCHEMA_ID('legacy') IS NULL EXEC ('CREATE SCHEMA legacy');"
    echo "GO"
    echo "IF OBJECT_ID('legacy.manifest') IS NULL"
    echo "    CREATE TABLE legacy.manifest ("
    echo "        table_name   sysname       NOT NULL PRIMARY KEY,"
    echo "        load_mode    varchar(11)   NOT NULL,  -- full, incremental"
    echo "        upsert_key   nvarchar(400) NULL,      -- the key the package used; for composite keys, missing a column"
    echo "        window_days  int           NULL       -- incremental: rows created or modified within this many days"
    echo "    );"
    echo "GO"
    echo
    echo "DELETE FROM legacy.manifest;"
    echo "INSERT INTO legacy.manifest (table_name, load_mode, upsert_key, window_days) VALUES"
    sql erp -d erp_sim -h -1 -W -Q "SET NOCOUNT ON;
        WITH kc AS (
            SELECT c.table_name, c.column_name, c.key_ordinal,
                   MAX(c.key_ordinal) OVER (PARTITION BY c.table_name) AS n_keys
            FROM dbo.design_column c WHERE c.role = 'key'),
        k AS (
            SELECT table_name,
                   STRING_AGG(IIF(key_ordinal < n_keys OR n_keys = 1, column_name, NULL), ', ') WITHIN GROUP (ORDER BY key_ordinal) AS upsert_key
            FROM kc GROUP BY table_name)
        SELECT CONCAT('    (''', d.table_name, ''', ',
                      IIF(d.row_count >= 20000 AND d.has_dates = 1,
                          CONCAT('''incremental'', ''', k.upsert_key, ''', ', IIF(dbo.rnd(s.seed, d.ordinal, 30) < 0.5, 7, 30)),
                          '''full'', NULL, NULL'),
                      ')', IIF(ROW_NUMBER() OVER (ORDER BY d.table_name DESC) = 1, ';', ','))
        FROM dbo.design_table d JOIN k ON k.table_name = d.table_name CROSS JOIN dbo.sim_state s
        ORDER BY d.table_name;"
    echo "GO"
} > "$out"
echo "wrote $out ($(grep -c "'incremental'" "$out") incremental, $(grep -c "'full'" "$out") full)"
